export function normalizeLocale(value) {
  return value === 'en' ? 'en' : 'zh';
}

export function createTranslator(initialLocale = DEFAULT_LOCALE) {
  let locale = normalizeLocale(initialLocale);

  function t(key, params = null) {
    const dict = MESSAGES[locale] || MESSAGES.zh;
    let text = dict[key] ?? MESSAGES.zh[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  }

  return {
    get locale() {
      return locale;
    },
    setLocale(next) {
      locale = normalizeLocale(next);
      return locale;
    },
    toggleLocale() {
      locale = locale === 'zh' ? 'en' : 'zh';
      return locale;
    },
    t,
  };
}

